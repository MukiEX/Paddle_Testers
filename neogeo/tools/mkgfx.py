"""Fix-layer graphics for the pad tester: font (tiles = ASCII code) and the
Neo Geo CD-style pad (tiles from $100), both into a 128 KB S ROM, plus the
pad tile map as an assembler include."""
import sys, numpy as np
from font import F57, MINI

W, H = 144, 80               # pad art: 18 x 10 tiles
E_UP, E_DOWN, E_LEFT, E_RIGHT, E_A, E_B, E_C, E_D, E_START, E_SELECT, E_COIN = range(4, 15)
OUT, BODY, HI, LABEL = 1, 2, 3, 15

def pad_art():
    img = np.zeros((H, W), np.uint8)
    yy, xx = np.mgrid[0:H, 0:W]
    def rrect(x0, y0, x1, y1, r):
        m = (xx >= x0) & (xx <= x1) & (yy >= y0) & (yy <= y1)
        for cx, cy in ((x0 + r, y0 + r), (x1 - r, y0 + r), (x0 + r, y1 - r), (x1 - r, y1 - r)):
            corner = ((xx < x0 + r) if cx == x0 + r else (xx > x1 - r)) & ((yy < y0 + r) if cy == y0 + r else (yy > y1 - r))
            m &= ~(corner & ((xx - cx) ** 2 + (yy - cy) ** 2 > r * r))
        return m
    def circle(cx, cy, r):
        return (xx - cx) ** 2 + (yy - cy) ** 2 <= r * r + r * 0.6
    def rect(x0, y0, x1, y1):
        return (xx >= x0) & (xx <= x1) & (yy >= y0) & (yy <= y1)
    def outline(m):
        g = np.zeros_like(m)
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            g |= np.roll(np.roll(m, dy, 0), dx, 1)
        return g & ~m
    def paint(m, c, ol=True):
        if ol:
            img[outline(m)] = OUT
        img[m] = c
    def text(s, x, y, c):
        for ch in s:
            for j, row in enumerate(MINI[ch]):
                for i, p in enumerate(row):
                    if p == '#':
                        img[y + j, x + i] = c
            x += 4

    # body
    body = rrect(3, 13, 140, 77, 22)
    paint(body, BODY)
    img[body & (yy < 30)] = HI
    # coin icon + label above the body
    paint(circle(10, 5, 4), E_COIN)
    img[3:8, 10] = OUT
    text("COIN", 17, 3, LABEL)
    # d-pad
    cx, cy, a = 30, 47, 5          # centre, half arm width
    L = 12                         # arm length
    centre = rect(cx - a, cy - a, cx + a, cy + a)
    arms = {E_UP: rect(cx - a, cy - a - L, cx + a, cy - a - 1), E_DOWN: rect(cx - a, cy + a + 1, cx + a, cy + a + L),
            E_LEFT: rect(cx - a - L, cy - a, cx - a - 1, cy + a), E_RIGHT: rect(cx + a + 1, cy - a, cx + a + L, cy + a)}
    cross = centre.copy()
    for m in arms.values():
        cross |= m
    img[outline(cross)] = OUT
    img[centre] = OUT
    for e, m in arms.items():
        img[m] = e
    # arrows on the arms
    for k in range(3):
        img[cy - a - L + 3 + k, cx - k:cx + k + 1] = LABEL          # up
        img[cy + a + L - 3 - k, cx - k:cx + k + 1] = LABEL          # down
        img[cy - k:cy + k + 1, cx - a - L + 3 + k] = LABEL          # left
        img[cy - k:cy + k + 1, cx + a + L - 3 - k] = LABEL          # right
    # select / start
    paint(rrect(49, 61, 60, 65, 2), E_SELECT)
    paint(rrect(68, 61, 79, 65, 2), E_START)
    text("SEL", 50, 54, LABEL)
    text("START", 65, 54, LABEL)
    # A B C D on an arc, like the Neo Geo CD pad
    for e, (bx, by), ch in ((E_A, (91, 62), 'A'), (E_B, (105, 57), 'B'), (E_C, (119, 52), 'C'), (E_D, (132, 46), 'D')):
        paint(circle(bx, by, 6), e)
        text(ch, bx - 1, by - 2, OUT)
    return img

def glyph_tile(rows, x0=1, y0=0):
    t = np.zeros((8, 8), np.uint8)
    for j, row in enumerate(rows):
        for i, p in enumerate(row):
            if p == '#':
                t[y0 + j, x0 + i] = 1
    return t

def srom_tile(t):
    out = bytearray()
    for x0 in (4, 6, 0, 2):
        for y in range(8):
            out.append(int(t[y, x0]) | (int(t[y, x0 + 1]) << 4))
    return bytes(out)

def main(srom_path, inc_path, png_path=None):
    rom = bytearray(0x20000)
    def put(n, t):
        rom[n * 32:(n + 1) * 32] = srom_tile(t)
    for ch, rows in F57.items():
        put(ord(ch), glyph_tile(rows))
    put(0x7f, np.pad(np.ones((6, 6), np.uint8), 1))      # solid block
    art = pad_art()
    tiles, mp = {}, []
    base = 0x100
    for ty in range(H // 8):
        for tx in range(W // 8):
            t = art[ty * 8:(ty + 1) * 8, tx * 8:(tx + 1) * 8]
            if not t.any():
                mp.append(0x20)                # blank = space glyph
                continue
            k = t.tobytes()
            if k not in tiles:
                tiles[k] = base + len(tiles)
                put(tiles[k], t)
            mp.append(tiles[k])
    open(srom_path, 'wb').write(rom)
    with open(inc_path, 'w') as f:
        f.write('; generated by mkgfx.py\nPAD_W equ %d\nPAD_H equ %d\npad_map:\n' % (W // 8, H // 8))
        for ty in range(H // 8):
            f.write('        dc.w    ' + ','.join('$%03x' % v for v in mp[ty * (W // 8):(ty + 1) * (W // 8)]) + '\n')
    if png_path:
        from PIL import Image
        pal = [(0, 0, 0), (17, 17, 17), (58, 58, 70), (74, 74, 88)] + [(255, 64, 64)] * 11 + [(200, 200, 208)]
        rgb = np.array(pal, np.uint8)[art]
        Image.fromarray(rgb).resize((W * 4, H * 4), 0).save(png_path)
    print('pad tiles:', len(tiles))

if __name__ == '__main__':
    main(*sys.argv[1:])
