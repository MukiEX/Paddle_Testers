#!/usr/bin/env python3
"""gen.py <out.h> : font texture (4bpp, two fonts) and a sine table for main.c.
Fonts are X11 misc-fixed (public domain): koi6x9 for text, koi8x16b for titles."""
import gzip, math, sys, os, tempfile
from PIL import PcfFontFile, ImageFont, Image, ImageDraw
def load(name):
    d = tempfile.mkdtemp()
    f = PcfFontFile.PcfFontFile(gzip.open('/usr/share/fonts/X11/cyrillic/%s.pcf.gz' % name)); f.compile(); f.save(os.path.join(d, name))
    return ImageFont.load(os.path.join(d, name + '.pil'))
tex = Image.new('L', (128, 192), 0)
for fi, (name, sh) in enumerate((('koi6x9', 1), ('koi8x16b', 0))):
    F = load(name)
    for c in range(32, 128):
        i = c - 32; x = (i % 16) * 8; y = fi * 96 + (i // 16) * 16
        cell = Image.new('L', (8, 16), 0)
        # PIL's PCF loader maps koi6x9 one code point high (sh); koi8x16b is fine
        ImageDraw.Draw(cell).text((0, 0), chr(c - sh), font=F, fill=255)
        tex.paste(cell, (x, y))
tex.save(os.path.join(os.path.dirname(sys.argv[1]), 'font_preview.png'))
px = tex.load(); words = []
for y in range(192):
    for x in range(0, 128, 8):
        w = 0
        for k in range(8):
            if px[x + k, y] > 127: w |= 1 << (k * 4)
        words.append(w)
sin = [round(4096 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
with open(sys.argv[1], 'w') as o:
    o.write('// generated by tools/gen.py\n')
    o.write('static const unsigned int font_tex[%d] = {\n' % len(words))
    for i in range(0, len(words), 8): o.write('  ' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + ',\n')
    o.write('};\nstatic const short sin_tab[256] = {\n')
    for i in range(0, 256, 16): o.write('  ' + ', '.join(str(v) for v in sin[i:i + 16]) + ',\n')
    o.write('};\n')
